function ai2_write_results(report, output_dir)
% Export numerical results and a LaTeX fragment, without serialising handles.
if ~exist(output_dir,'dir'), mkdir(output_dir); end
save(fullfile(output_dir,'results.mat'),'report','-v7');
fid = fopen(fullfile(output_dir,'summary.csv'),'w');
assert(fid >= 0,'ai2:Output','Cannot open summary.csv');
guard = onCleanup(@() fclose(fid));
fprintf(fid,'condition,n,accuracy,informative_probe_rate,mean_posterior_true,mean_execution_rmse\n');
for s = report.summary
    fprintf(fid,'%s,%d,%.12g,%.12g,%.12g,%.12g\n',s.condition,s.n,s.accuracy, ...
        s.informative_probe_rate,s.mean_posterior_true,s.mean_execution_rmse);
end
clear guard
fid = fopen(fullfile(output_dir,'trials.csv'),'w');
assert(fid >= 0,'ai2:Output','Cannot open trials.csv');
guard = onCleanup(@() fclose(fid));
fprintf(fid,'condition,truth,trial,probe,selected,correct,sensor_outcome,q1_initial,q1_after_probe,q2_after_probe,execution_rmse\n');
for r = report.runs
    fprintf(fid,'%s,%d,%d,%d,%d,%d,%d,%.12g,%.12g,%.12g,%.12g\n', ...
        r.condition,r.truth,r.trial,r.probe,r.selected,r.correct,r.sensor_outcome, ...
        r.prior_online(1),r.posterior_after_probe(1),r.posterior_after_probe(2),r.execution_rmse);
end
clear guard

fid = fopen(fullfile(output_dir,'two_neuron_summary.tex'),'w');
assert(fid >= 0,'ai2:Output','Cannot open LaTeX summary');
guard = onCleanup(@() fclose(fid));
lines = {
    '% Generated by ai2_write_results.m. Values refer to this seeded experiment.'
    '\subsection{Results of the first experiment}'
    'The model uses two target networks with $W_1=\operatorname{diag}(2,-2)$,'
    '$V_1=-W_1$, $W_2=-W_1$, $V_2=-V_1$, zero biases and $\tau=5$.'
    'Four connections are made programmable in the physical interpreter of 14 neurons.'
    'The neutral stimulus is $(0.5,0.5)$; the informative stimulus is $(0.9,0.5)$.'
    'SPM selects the stimulus and then one of the two codes; success feedback is provided only at the end.'
    'The observed process uses the target networks, whereas the internal likelihood is calibrated using the interpreter.'
    'Gaussian sensor noise is discretized into two outcomes; the CTRNN dynamics are deterministic.'
    sprintf('Seed: \\texttt{%d}; %d episodes per context and condition. Every episode restarts from the same prior.',report.config.seed,report.config.trials_per_context)
    '\begin{table}[htbp]'
    '\centering\small'
    '\begin{tabular}{lrrrr}'
    '\toprule'
    'Condition & Episodes & Correct choice & Informative probe & Execution RMSE \\'
    '\midrule'
    };
for k = 1:numel(report.summary)
    s = report.summary(k);
    lines{end+1} = sprintf('%s & %d & %.3f & %.3f & %.5f \\\\', ...
        s.condition,s.n,s.accuracy,s.informative_probe_rate,s.mean_execution_rmse);
end
lines = [lines; {
    '\bottomrule'
    '\end{tabular}'
    '\caption[Hypothesis A: program selection and execution]{Program selection and execution in hypothesis A. The sensor likelihood follows Eq.~\eqref{eq:a-observation}; execution error is measured by Eq.~\eqref{eq:emulation-rmse}. Results are exported by \texttt{ai2\_write\_results.m} from \texttt{run\_two\_neuron\_active\_inference.m}.}'
    '\label{tab:a-results}'
    '\end{table}'
    'The \texttt{passive} condition allows only the neutral stimulus; it is not an ablation of the epistemic term in SPM.'
    'The \texttt{oracle} condition knows the correct program from the outset.'
    'Post-probe beliefs are extracted before terminal feedback, avoiding retrospective information.'
    sprintf('RMSE with the correct code under the informative stimulus: %.5f and %.5f for the two contexts.',report.execution_rmse(1,1),report.execution_rmse(2,2))
    'Multiplier errors also produce a small difference between contextual predictions under the neutral stimulus,'
    'which is absent from the target process. This mismatch is retained in the test, without correction using the true response.'
    'The rates describe this sample with a fixed seed; they do not establish general superiority.'
    'The test concerns a finite family of two codes. The interpreter does not yet perform free-energy updates: SPM performs them.'
    '\IfFileExists{results/two_neuron_demo.png}{%'
    '\begin{figure}[htbp]\centering'
    '\includegraphics[width=\linewidth]{results/two_neuron_demo.png}'
    '\caption[Hypothesis A: trajectories, performance and programs]{Target and interpreter trajectories for the CTRNN dynamics in Eq.~\eqref{eq:ctrnn}, program-selection performance, and normalized codes from Eq.~\eqref{eq:program-code}. Figure generated by \texttt{ai2\_plot\_results.m}.}'
    '\label{fig:a-results}\end{figure}}{}'
    }];
fprintf(fid,'%s\n',lines{:});
end
