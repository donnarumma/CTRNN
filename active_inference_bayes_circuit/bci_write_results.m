function bci_write_results(report,output_dir)
% Export raw outputs, diagnostic metrics, and a reproducible LaTeX fragment.
if ~exist(output_dir,'dir'), mkdir(output_dir); end
save(fullfile(output_dir,'results.mat'),'report','-v7');
fid=fopen(fullfile(output_dir,'posteriors.csv'),'w');
assert(fid>=0,'bci:Output','Cannot write posteriors.csv');
guard=onCleanup(@() fclose(fid));
fprintf(fid,['model,group,observation,p_high_h1,p_high_h2,bayes_h1,bayes_h2,' ...
    'raw_h1,raw_h2,decoded_h1,decoded_h2,spm_h1,spm_h2,raw_error,' ...
    'normalization_error,diagnostic_kl,max_diagnostic_F_step_increase\n']);
for e=report.episodes
    fprintf(fid,'%s,%s,%d,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n', ...
        e.name,e.group,e.observation,e.likelihood_high,e.bayes,e.raw_final,e.decoded_final, ...
        e.spm_posterior,e.raw_error,e.normalization_error,e.final_kl,e.max_free_energy_increase);
end
clear guard
fid=fopen(fullfile(output_dir,'summary.csv'),'w');
assert(fid>=0,'bci:Output','Cannot write summary.csv');
guard=onCleanup(@() fclose(fid));
fprintf(fid,'metric,value\n'); fields=fieldnames(report.summary);
for k=1:numel(fields), fprintf(fid,'%s,%.12g\n',fields{k},report.summary.(fields{k})); end
if isfield(report,'sensitivity')
    fprintf(fid,'half_dt_max_change,%.12g\n',max(report.sensitivity.half_dt_change));
    fprintf(fid,'narrow_range_anchor_max_raw_error,%.12g\n',max(report.sensitivity.narrow_raw_error));
end
clear guard
fid=fopen(fullfile(output_dir,'programs.csv'),'w');
assert(fid>=0,'bci:Output','Cannot write programs.csv');
guard=onCleanup(@() fclose(fid));
fprintf(fid,'model,p_high_h1,p_high_h2,E11,E12,E21,E22,code11,code12,code21,code22\n');
for k=1:size(report.models,1)
    fprintf(fid,'%d,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n', ...
        k,report.models(k,:),report.weights(k,:),report.programs(k,:));
end
clear guard
fid=fopen(fullfile(output_dir,'bayes_circuit_summary.tex'),'w');
assert(fid>=0,'bci:Output','Cannot write TeX fragment');
guard=onCleanup(@() fclose(fid));
lines={
    '% Generated by bci_write_results.m; do not edit numerical values manually.'
    'The table reports the \emph{high} observation under a uniform prior. The two raw outputs are neural activities;'
    'their sum can differ from one because of the multiplier approximation. SPM agrees with Bayes to numerical precision.'
    '\begin{table}[htbp]\centering\small'
    '\begin{tabular}{lrrrr}'
    '\toprule'
    'Model & Bayes $q_1$ & CTRNN $r_1$ & CTRNN $r_2$ & $r_1+r_2$ \\'
    '\midrule'};
for k=1:2:8
    e=report.episodes(k);
    lines{end+1}=sprintf('%s & %.3f & %.5f & %.5f & %.5f \\\\', ...
        e.name,e.bayes(1),e.raw_final,sum(e.raw_final));
end
lines=[lines; {
    '\bottomrule\end{tabular}'
    '\caption[Hypothesis B1: exact posterior and raw neural outputs]{Exact posterior from Eq.~\eqref{eq:b1-bayes} and raw interpreted activities for the circuit in Eqs.~\eqref{eq:b1-weights} and~\eqref{eq:b1-relaxation}, under the high observation and a uniform prior. Table exported by \texttt{bci\_write\_results.m}.}'
    '\label{tab:b1-results}\end{table}'}];
s=report.summary;
lines{end+1}=sprintf('The test covers %d cases: four illustrative models and a grid of %d models, each with two observations.',s.n_observations,s.n_grid_models);
lines{end+1}='Two illustrative models also occur on the grid: the default test contains 27 distinct models.';
lines{end+1}=sprintf('The maximum absolute error of the raw outputs at the end of a trial is %.5f; the maximum normalization defect along the trajectories is %.5f.',s.max_raw_error,s.max_normalization_error);
lines{end+1}=sprintf('The maximum final KL, computed only as a diagnostic on the externally normalized pair, is %.6f nat.',s.max_final_kl);
lines{end+1}=sprintf('The dedicated circuit converges to the analytical posterior with a maximum error of %.3g; the maximum discrepancy of the SPM reference is %.3g.',s.max_target_error,s.max_spm_error);
lines{end+1}=sprintf('The dedicated circuit reduces free energy, but the interpreter shows transient increases: the maximum per step is %.6f nat.',s.max_free_energy_increase);
lines{end+1}='These increases prevent extending the monotonicity established for the ideal circuit to the full approximate interpreter.';
if isfield(report,'sensitivity')
    lines{end+1}=sprintf('Across the four illustrative models, halving the step changes the final outputs by at most %.3g; narrowing the range to $[-2,2]$ produces a maximum raw error of %.5f.', ...
        max(report.sensitivity.half_dt_change),max(report.sensitivity.narrow_raw_error));
end
lines=[lines; {
    '\IfFileExists{results_bayes/bayes_circuit_demo.png}{%'
    '\begin{figure}[htbp]\centering'
    '\includegraphics[width=\linewidth]{results_bayes/bayes_circuit_demo.png}'
    '\caption[Hypothesis B1: neural activities and inference errors]{Raw neural activities compared with the ideal relaxation in Eq.~\eqref{eq:b1-relaxation}, posterior error across the likelihood grid relative to Eq.~\eqref{eq:b1-bayes}, and diagnostic KL after external normalization as in Eq.~\eqref{eq:b1-normalized}. Figure generated by \texttt{bci\_plot\_results.m}.}'
    '\label{fig:b1-results}\end{figure}}{}'}];
if isfield(report,'validation') && report.validation.reference_independence
    lines{end+1}='Disabling the SPM reference leaves the trajectories of the four illustrative models unchanged: the reference does not supply inputs to the network.';
end
fprintf(fid,'%s\n',lines{:});
end
