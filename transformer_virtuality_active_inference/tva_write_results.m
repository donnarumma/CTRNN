function tva_write_results(report,output_dir)
% Export exact enumeration and an English, equation-linked LaTeX fragment.
if ~exist(output_dir,'dir'), mkdir(output_dir); end
save(fullfile(output_dir,'results.mat'),'report','-v7');
fid=fopen(fullfile(output_dir,'results.json'),'w'); assert(fid>=0,'tva:Write','Cannot open JSON.');
guard=onCleanup(@() fclose(fid)); fprintf(fid,'%s\n',jsonencode(report)); clear guard
write_rows(fullfile(output_dir,'summary.csv'),report.summary);
write_rows(fullfile(output_dir,'trials.csv'),report.trials);
write_rows(fullfile(output_dir,'cost_sweep.csv'),report.cost_sweep);
fid=fopen(fullfile(output_dir,'tva_summary.tex'),'w'); assert(fid>=0,'tva:Write','Cannot open LaTeX output.');
guard=onCleanup(@() fclose(fid));
fprintf(fid,'%% Generated by tva_write_results.m; numerical values come from exact enumeration.\n');
fprintf(fid,'The evaluation enumerates both known sensor modes, all six payload permutations, all three hidden rules, action choices, and all three sensor outcomes. No Monte Carlo sampling or fitting is used.\n\n');
fprintf(fid,'\\begin{table}[htbp]\\centering\\footnotesize\n\\begin{tabular}{lrrrrr}\\toprule\n');
fprintf(fid,'Condition & Accuracy & Paid probes & Cost & Decision NLL & Bayes NLL \\\\\n\\midrule\n');
for s=report.summary
    label=strrep(s.condition,'_','\_');
    fprintf(fid,'\\texttt{%s} & %.4f & %.3f & %.3f & %.4f & %.4f \\\\\n', ...
        label,s.accuracy,s.paid_probe,s.cost,s.classhead_nll,s.bayes_predictive_nll);
end
fprintf(fid,'\\bottomrule\\end{tabular}\n');
fprintf(fid,['\\caption[Active sensing and runtime program execution]{Exact expected performance in the hidden-rule model, Equation~\\eqref{eq:tva-model}. ' ...
    'Action selection uses Equation~\\eqref{eq:tva-efe}; the attention posterior supplies the program in Equation~\\eqref{eq:tva-program}. ' ...
    'Execution and the decision head follow Equations~\\eqref{eq:tva-execution} and~\\eqref{eq:tva-readout}. ' ...
    'Costs and negative log likelihoods are in nats. MATLAB producers: \\path{run_tva_rule_task.m} and \\path{tva_write_results.m}.}\\label{tab:tva-results}\\end{table}\n\n']);
fprintf(fid,'Active and random probing use the same number of paid observations and the same cost. The no-epistemic condition retains the same action set and costs but removes information gain; passive observation is a separate control.\n');
fprintf(fid,'The three fixed-program conditions acquire the active probe but freeze the execution coefficients at each possible selector. Their sensor posteriors remain available only for diagnostic comparison. The matched compiled bank uses the same posterior and is numerically equivalent to the shared interpreter.\n');
fprintf(fid,'Bayes NLL refers to the exact posterior-predictive mixture before a fixed-program override. Decision NLL refers to the actual post-normalized block and class softmax; these distributions are distinct even when their maximizing class agrees. Tied decisions contribute fractional correctness.\n');
if isfield(report,'validation')
    fprintf(fid,'The numerical checks passed; maximum posterior, scalar/matrix, and joint-preference EFE errors are %.3g, %.3g, and %.3g, respectively.\n', ...
        report.validation.max_bayes_error,report.validation.max_scalar_matrix_error,report.validation.max_efe_identity_error);
end
if isfield(report,'spm')
    fprintf(fid,'The separate single-observation SPM reference agrees with the attention posteriors to a maximum absolute error of %.3g; it does not supply the operative programs or policies.\n',report.spm.maxerror);
end
end

function write_rows(pathname,rows)
fid=fopen(pathname,'w'); assert(fid>=0,'tva:Write','Cannot open CSV.');
guard=onCleanup(@() fclose(fid));
fields=fieldnames(rows); headers={};
for k=1:numel(fields)
    value=rows(1).(fields{k});
    if ischar(value) || isscalar(value), headers{end+1}=fields{k}; %#ok<AGROW>
    else
        for j=1:numel(value), headers{end+1}=sprintf('%s_%d',fields{k},j); end %#ok<AGROW>
    end
end
fprintf(fid,'%s\n',strjoin(headers,','));
for row=rows
    parts={};
    for k=1:numel(fields)
        value=row.(fields{k});
        if ischar(value), parts{end+1}=['"' strrep(value,'"','""') '"']; %#ok<AGROW>
        else
            for j=1:numel(value), parts{end+1}=sprintf('%.17g',value(j)); end %#ok<AGROW>
        end
    end
    fprintf(fid,'%s\n',strjoin(parts,','));
end
end
