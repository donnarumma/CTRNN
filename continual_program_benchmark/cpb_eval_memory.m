function values=cpb_eval_memory(q_codes,cue_counts,seen,true_codes,peak_symbols,motor,p,c)
%CPB_EVAL_MEMORY Evaluator integrates outcomes; hidden labels never enter recognition.
idx=find(seen); values=zeros(numel(idx),8);
for observation=1:6
 decision=cpb_recognize(cue_counts,q_codes,seen,observation,p);
 for local=1:numel(idx)
  j=idx(local); truth=true_codes(j);
  mass=(1-c.cue_reliability)/5;
  if observation==peak_symbols(j), mass=c.cue_reliability; end
  [~,oracle_context_code]=max(q_codes(j,:));
  target=zeros(1,6); target(truth)=1;
  values(local,:)=values(local,:)+mass*[ ...
   motor.success(decision.predicted_code,truth), ...
   motor.success(oracle_context_code,truth), ...
   double(decision.predicted_context==j), ...
   -log(max(realmin,decision.q_program(truth))), ...
   sum((decision.q_program-target).^2), ...
   motor.cost(decision.predicted_code,truth), ...
   -log(max(realmin,q_codes(j,truth))), ...
   motor.success(truth,truth)];
 end
end
end
