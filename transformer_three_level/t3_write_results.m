function t3_write_results(report, output_dir)
%T3_WRITE_RESULTS Export exact data and an English LaTeX report fragment.
if ~exist(output_dir,'dir'), mkdir(output_dir); end
save(fullfile(output_dir,'results.mat'),'report','-v7');
fid=fopen(fullfile(output_dir,'results.json'),'w');
assert(fid>=0,'t3:Write','Cannot open JSON export.');
guard=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(report)); clear guard
matrices=struct('X',report.inputs.X,'Q',report.stage1.Q,'K',report.stage1.K, ...
    'V',report.stage1.V,'key_program',report.stage2.key_program,'scores',report.stage2.scores, ...
    'scaled_scores',report.stage2.scaled_scores,'A',report.stage2.A,'Z',report.stage3.Z, ...
    'projected',report.downstream.projected,'residual1',report.downstream.residual1, ...
    'U',report.downstream.U,'ffn_hidden',report.downstream.ffn_hidden, ...
    'ffn_output',report.downstream.ffn_output,'residual2',report.downstream.residual2,'Y',report.downstream.Y, ...
    'readout_logits',report.readout.logits,'readout_probabilities',report.readout.probabilities, ...
    'readout_prediction_indices',report.readout.prediction_indices);
parameters=fieldnames(report.fixed_parameters);
for k=1:numel(parameters), matrices.(parameters{k})=report.fixed_parameters.(parameters{k}); end
names=fieldnames(matrices);
for k=1:numel(names), write_csv(fullfile(output_dir,[names{k} '.csv']),matrices.(names{k})); end
fid=fopen(fullfile(output_dir,'t3_summary.tex'),'w');
assert(fid>=0,'t3:Write','Cannot open TeX export.');
guard=onCleanup(@() fclose(fid));
fprintf(fid,'%% Generated by t3_write_results.m; numerical values are not edited manually.\n');
fprintf(fid,'The example uses three tokens with three features each, one attention head, and a shared $3\\to6\\to3$ feed-forward network. ');
fprintf(fid,'All projection and feed-forward parameters are hand-chosen constants; no training is performed. ');
fprintf(fid,'Attention is bidirectional, with no mask or positional encoding. The three levels are functional stages within one head, not three stacked Transformer blocks.\n\n');
fprintf(fid,'\\begin{table}[htbp]\\centering\\small\n\\renewcommand{\\arraystretch}{1.35}\n');
fprintf(fid,'\\begin{tabular}{lc}\\toprule\nQuantity & Numerical value \\\\\n\\midrule\n');
labels={'Input $X$','Attention program $A$','Head output $Z$','Block output $Y$'};
values={report.inputs.X,report.stage2.A,report.stage3.Z,report.downstream.Y};
for k=1:numel(labels)
    fprintf(fid,'%s & $%s$ \\\\[0.5em]\n',labels{k},tex_matrix(values{k}));
end
fprintf(fid,'\\bottomrule\\end{tabular}\n');
fprintf(fid,['\\caption[Three-token example: input, attention, head, and block outputs]{Numerical matrices for the three-token example. ' ...
    'The fixed projections are defined in Equation~\\eqref{eq:t3-projections}; ' ...
    '$A$ and $Z$ follow Equations~\\eqref{eq:t3-attention} and~\\eqref{eq:t3-execution}. ' ...
    '$Y$ includes the output projection, residual paths, row-wise LayerNorm, and shared feed-forward sublayer ' ...
    '(Equations~\\eqref{eq:t3-postnorm} through~\\eqref{eq:t3-block-output}). ' ...
    'Values are rounded to four decimals here; full precision is retained in the CSV/JSON/MAT exports. ' ...
    'MATLAB producers: \\path{run_t3_example.m} (computation) and \\path{t3_write_results.m} (this table).}\n' ...
    '\\label{tab:t3-numeric}\\end{table}\n\n']);
fprintf(fid,'A separate illustrative vocabulary head maps each three-feature block output to four symbol probabilities. Its weights are hand-chosen and untrained; these probabilities do not make the example a trained language model.\n\n');
fprintf(fid,'\\begin{table}[htbp]\\centering\\small\n\\begin{tabular}{lrrrrl}\\toprule\n');
fprintf(fid,'Token & alpha & beta & gamma & delta & Prediction \\\\\n\\midrule\n');
for token=1:size(report.readout.probabilities,1)
    fprintf(fid,'$t_%d$ & %.4f & %.4f & %.4f & %.4f & %s \\\\\n',token, ...
        report.readout.probabilities(token,:),report.readout.predicted_symbols{token});
end
fprintf(fid,['\\bottomrule\\end{tabular}\n' ...
    '\\caption[Illustrative four-symbol vocabulary readout]{Final symbol probabilities from the linear $3\\to4$ readout and row-wise softmax ' ...
    'in Equation~\\eqref{eq:t3-readout}. Columns index vocabulary symbols, whereas columns of the attention matrix index source tokens. ' ...
    'This head is illustrative and untrained. MATLAB producers: \\path{t3_vocabulary_readout.m} (computation) and ' ...
    '\\path{t3_write_results.m} (this table).}\\label{tab:t3-readout}\\end{table}\n\n']);
if isfield(report,'validation')
    scientific = regexp(sprintf('%.2e',report.validation.max_scalar_vectorized_error), ...
        '^(.+)e([+-]\d+)$','tokens','once');
    fprintf(fid,'The independent scalar-loop and vectorized implementations agree to a maximum absolute difference of $%s\\times 10^{%d}$. ', ...
        scientific{1},str2double(scientific{2}));
    fprintf(fid,'The checks also verify positive normalized attention rows, query and context effects with fixed parameters, controlled key/attention program swaps, token-permutation equivariance, feature-wise LayerNorm, and token-wise feed-forward locality.\n');
end
fprintf(fid,'This example uses exact scalar multiplication. It does not implement or validate the historical approximate CTRNN multiplier, and it makes no active-inference claim.\n');
end

function write_csv(pathname,M)
fid=fopen(pathname,'w'); assert(fid>=0,'t3:Write','Cannot open CSV export.');
guard=onCleanup(@() fclose(fid)); %#ok<NASGU>
for row=1:size(M,1)
    for column=1:size(M,2)
        if column>1, fprintf(fid,','); end
        fprintf(fid,'%.17g',M(row,column));
    end
    fprintf(fid,'\n');
end
end

function text=tex_matrix(M)
text='\begin{bmatrix}';
for row=1:size(M,1)
    if row>1, text=[text ' \\ ']; end %#ok<AGROW>
    for column=1:size(M,2)
        if column>1, text=[text ' & ']; end %#ok<AGROW>
        value=M(row,column); if abs(value)<.00005, value=0; end
        text=[text sprintf('%.4f',value)]; %#ok<AGROW>
    end
end
text=[text '\end{bmatrix}'];
end
